class TestIssueDetection:
    def test_high_unreviewed_triggers_warning(self, client: TestClient):
        pid = _project(client)
        # Create multiple auto-extracted memories (>50% of total)
        sid = _session(
            client, pid,
            "We decided to use FastAPI. We also decided to use SQLite. "
            "We must use Docker for deployment. This is a critical architecture decision."
        )
        client.post(f"/sessions/{sid}/extract-memories")
        h = _health(client, pid)
        codes = [i["code"] for i in h["issues"]]
        # If extraction produced >50% auto_extracted, this should fire
        if h["review_breakdown"]["auto_extracted"] > h["active_count"] // 2:
            assert "high_unreviewed_count" in codes

    def test_high_unreviewed_absent_when_majority_verified(self, client: TestClient):
        pid = _project(client)
        sid = _session(client, pid, "We decided to use FastAPI for the backend.")
        result = client.post(f"/sessions/{sid}/extract-memories").json()
        # Verify all extracted memories
        for m in result["memories"]:
            client.put(f"/memories/{m['id']}", json={"review_status": "verified"})
        h = _health(client, pid)
        codes = [i["code"] for i in h["issues"]]
        assert "high_unreviewed_count" not in codes

    def test_low_avg_quality_triggers_warning(self, client: TestClient):
        pid = _project(client)
        # Create minimal memories with very low quality scores
        for i in range(5):
            _mem(client, pid, title="X", content="Y" * 5)
        h = _health(client, pid)
        if h["avg_quality_score"] is not None and h["avg_quality_score"] < 0.40:
            codes = [i["code"] for i in h["issues"]]
            assert "low_avg_quality" in codes

    def test_rejected_memories_issue_fires(self, client: TestClient):
        pid = _project(client)
        sid = _session(client, pid, "We decided to use Redis for caching.")
        result = client.post(f"/sessions/{sid}/extract-memories").json()
        if result["memories"]:
            client.put(f"/memories/{result['memories'][0]['id']}", json={"review_status": "rejected"})
        h = _health(client, pid)
        codes = [i["code"] for i in h["issues"]]
        assert "rejected_memories_present" in codes

    def test_low_traceability_issue_fires(self, client: TestClient):
        pid = _project(client)
        # All memories with no source ref
        for i in range(5):
            _mem(client, pid,
                 title=f"Untraceable memory {i}",
                 content="Memory without any source traceability information.")
        h = _health(client, pid)
        codes = [i["code"] for i in h["issues"]]
        assert "low_traceability" in codes

    def test_low_traceability_absent_when_traced(self, client: TestClient):
        pid = _project(client)
        # All memories with source_type → traced
        for i in range(5):
            _mem(client, pid,
                 title=f"Traced memory {i}",
                 content="Memory with proper source attribution and traceability.",
                 source_type="manual")
        h = _health(client, pid)
        codes = [i["code"] for i in h["issues"]]
        assert "low_traceability" not in codes

    def test_issue_has_severity_and_message(self, client: TestClient):
        pid = _project(client)
        for i in range(4):
            _mem(client, pid, title="X", content="Y" * 5)
        h = _health(client, pid)
        for issue in h["issues"]:
            assert "severity" in issue
            assert "code" in issue
            assert "message" in issue
            assert issue["severity"] in ("warning", "info")



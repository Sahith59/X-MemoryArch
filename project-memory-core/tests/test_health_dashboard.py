def _project(client: TestClient, name: str = "Health Test Project") -> str:
    r = client.post("/projects", json={"name": name})
    assert r.status_code == 201
    return r.json()["id"]


def _mem(
    client: TestClient,
    pid: str,
    *,
    title: str = "Health test memory",
    content: str = "Some content for health testing here.",
    mem_type: str = "decision",
    importance: int = 3,
    confidence: float = 0.80,
    status: str = "active",
    tags: list[str] | None = None,
    file_path: str | None = None,
    symbol_name: str | None = None,
    type_metadata: dict | None = None,
    source_type: str | None = None,
    source_quote: str | None = None,
    review_status: str | None = None,
) -> dict:
    body: dict = {
        "type": mem_type,
        "title": title,
        "content": content,
        "importance": importance,
        "confidence": confidence,
        "status": status,
        "tags": tags or [],
    }
    for k, v in [
        ("file_path", file_path),
        ("symbol_name", symbol_name),
        ("type_metadata", type_metadata),
        ("source_type", source_type),
        ("source_quote", source_quote),
        ("review_status", review_status),
    ]:
        if v is not None:
            body[k] = v
    r = client.post(f"/projects/{pid}/memories", json=body)
    assert r.status_code == 201, r.text
    return r.json()


def _session(client: TestClient, pid: str, content: str) -> str:
    r = client.post(f"/projects/{pid}/sessions", json={
        "tool_name": "Claude",
        "title": "Health Test Session",
        "raw_content": content,
        "session_date": "2026-05-25",
    })
    assert r.status_code == 201
    return r.json()["id"]


def _health(client: TestClient, pid: str) -> dict:
    r = client.get(f"/projects/{pid}/health")
    assert r.status_code == 200, r.text
    return r.json()



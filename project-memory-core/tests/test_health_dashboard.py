class TestEmptyProject:
    def test_empty_project_returns_zeroed_report(self, client: TestClient):
        pid = _project(client)
        h = _health(client, pid)
        assert h["total_memories"] == 0
        assert h["active_count"] == 0
        assert h["avg_quality_score"] is None
        assert h["avg_confidence"] is None
        assert h["low_confidence_count"] == 0
        assert h["type_distribution"] == {}

    def test_empty_project_has_no_issues(self, client: TestClient):
        pid = _project(client)
        h = _health(client, pid)
        issue_codes = [i["code"] for i in h["issues"]]
        assert "stale_active_memories" not in issue_codes
        assert "low_avg_quality" not in issue_codes

    def test_empty_project_traceability_zero(self, client: TestClient):
        pid = _project(client)
        h = _health(client, pid)
        assert h["pct_with_session_ref"] == 0.0
        assert h["pct_with_source_quote"] == 0.0
        assert h["pct_with_source_type"] == 0.0



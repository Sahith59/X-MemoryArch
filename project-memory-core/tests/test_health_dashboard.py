class TestQualityMetrics:
    def test_quality_buckets_sum_to_active_count(self, client: TestClient):
        pid = _project(client)
        for i in range(3):
            _mem(client, pid, title=f"Quality bucket test {i}", content="Content for bucketing test.")
        h = _health(client, pid)
        b = h["quality_buckets"]
        bucket_sum = b["excellent"] + b["good"] + b["fair"] + b["poor"]
        assert bucket_sum == h["active_count"]

    def test_rich_memory_lands_in_excellent_bucket(self, client: TestClient):
        pid = _project(client)
        # Enough signals to push quality_score >= 0.75:
        # title(>=50)=+0.20, content(>=200)=+0.15, type_metadata=+0.10, tags=+0.05,
        # source_quote=+0.05, source_type=+0.05, file_path=+0.10, symbol_name=+0.05,
        # related_files=+0.05, confidence=0.8*0.05=+0.04 → ~0.84
        _mem(
            client, pid,
            title="We decided to use FastAPI as the primary backend web framework for this project",
            content=(
                "After thorough evaluation of multiple web frameworks including Flask, Django REST "
                "Framework, and FastAPI, we selected FastAPI because of its native async support, "
                "type safety, and automatic OpenAPI documentation generation. This is a critical "
                "architecture decision that affects every API endpoint we build."
            ),
            tags=["structure"],
            file_path="app/main.py",
            symbol_name="create_app",
            type_metadata={"rationale": "async support", "alternatives_considered": ["Flask", "DRF"]},
            source_type="manual",
            source_quote="We decided to use FastAPI because of performance and type safety.",
        )
        h = _health(client, pid)
        assert h["quality_buckets"]["excellent"] >= 1

    def test_minimal_memory_lands_in_poor_bucket(self, client: TestClient):
        pid = _project(client)
        _mem(client, pid, title="A", content="B" * 5)
        h = _health(client, pid)
        assert h["quality_buckets"]["poor"] >= 1

    def test_avg_quality_score_is_mean(self, client: TestClient):
        pid = _project(client)
        m1 = _mem(client, pid, title="M1", content="Short content test.")
        m2 = _mem(client, pid, title="M2 which is a longer title for testing quality scores", content="A" * 250)
        expected_avg = round((m1["quality_score"] + m2["quality_score"]) / 2, 3)
        h = _health(client, pid)
        assert abs(h["avg_quality_score"] - expected_avg) < 0.005

    def test_superseded_memories_excluded_from_quality_avg(self, client: TestClient):
        pid = _project(client)
        m = _mem(client, pid, title="Original to supersede", content="Content to be superseded soon.")
        client.post(f"/memories/{m['id']}/supersede", json={
            "type": "decision",
            "title": "New superseding version of this memory",
            "content": "The replacement content for the superseded memory entry.",
        })
        h = _health(client, pid)
        # 1 active, 1 superseded — quality metrics should only cover the 1 active
        assert h["active_count"] == 1
        assert h["superseded_count"] == 1



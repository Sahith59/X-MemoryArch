"""
Sub-phase 1.16 Stress Tests — Memory Health Dashboard.

Tests every metric and issue generated by GET /projects/{id}/health:
  1.  Empty project yields zeroed counters with no crash
  2.  Status counts are accurate (active / resolved / stale / archived / superseded)
  3.  Quality buckets bin correctly
  4.  avg_quality_score is the mean of active memories' quality scores
  5.  Review status breakdown counts auto_extracted vs verified
  6.  Traceability percentages are accurate
  7.  Type distribution contains correct counts by memory type
  8.  avg_confidence and low_confidence_count are correct
  9.  Issue: high_unreviewed_count fires when >50% are auto_extracted
  10. Issue: high_unreviewed_count absent when majority are verified
  11. Issue: stale_active_memories fires for memories not updated in 30+ days
  12. Issue: low_avg_quality fires when average quality < 0.40
  13. Issue: low_traceability fires when >60% lack source reference
  14. Issue: rejected_memories_present fires when any memory is rejected
  15. generated_at is present and ISO-format datetime
  16. 404 for non-existent project
  17. Superseded memories appear in superseded_count, not active_count
  18. Resolved memories appear in resolved_count
  19. Quality buckets sum to active_count
  20. Health endpoint does not count superseded memories in quality metrics
"""
